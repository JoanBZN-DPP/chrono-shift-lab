const assert = require('node:assert/strict');
const fs = require('node:fs');
const cp = require('node:child_process');
const os = require('node:os');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const config = fs.readFileSync(path.join(root, 'firebase-config.js'), 'utf8');
const rules = JSON.parse(fs.readFileSync(path.join(root, 'firebase.rules.json'), 'utf8'));
const firstInline = html.indexOf('<script>', html.indexOf('firebase-config.js'));
const closeInline = html.lastIndexOf('</script>');
const jsFile = path.join(os.tmpdir(), `chrono-shift-${process.pid}.js`);
fs.writeFileSync(jsFile, html.slice(firstInline + 8, closeInline));
cp.execFileSync(process.execPath, ['--check', jsFile], { stdio: 'ignore' });
fs.rmSync(jsFile, { force: true });
assert.equal((html.match(/\{n:'\d+ ·/g) || []).length, 30);
assert.ok(html.includes('firebase.database(firebaseApp)'));
assert.ok(html.includes('.info/serverTimeOffset'));
assert.ok(html.includes('signInWithPopup'));
assert.ok(html.includes('signInWithRedirect'));
assert.ok(html.includes('linkWithPopup'));
assert.ok(html.includes('linkWithRedirect'));
assert.ok(html.includes('credential-already-in-use'));
assert.ok(html.includes('provider-already-linked'));
assert.match(html, /id="admb"[^>]*onclick="adminGate\(\)"/);
assert.doesNotMatch(html.match(/id="admb"[^>]*>/)?.[0] || '', /display:\s*none/);
assert.ok(html.includes('Abrir panel de administración'));
assert.ok(html.includes('firebaseReady=false'));
assert.ok(html.includes('ADMIN_EMAIL'));
assert.ok(html.includes('Persistence.NONE'));
assert.ok(html.includes('adminDb'));
assert.ok(html.includes('withTimeout'));
assert.ok(html.includes('netGeneration'));
assert.ok(html.includes('detachNetListeners'));
assert.doesNotMatch(html, /ADMIN_KEY|hashAdmin|localStorage.*admin/);
const sandbox = { window: {} };
require('node:vm').runInNewContext(config, sandbox);
const publicConfig = sandbox.window.CHRONO_FIREBASE_CONFIG;
assert.equal(publicConfig.projectId, 'chrono-shift-lab');
assert.equal(publicConfig.authDomain, 'chrono-shift-lab.firebaseapp.com');
assert.equal(publicConfig.databaseURL, 'https://chrono-shift-lab-default-rtdb.firebaseio.com');
assert.ok(publicConfig.apiKey && publicConfig.appId);
assert.ok(!config.includes('CHRONO_ADMIN_EMAIL'));
assert.equal(rules.rules['.read'], false);
assert.equal(rules.rules['.write'], false);
assert.match(rules.rules.admins['$uid']['.read'], /auth\.uid == \$uid/);
assert.equal(rules.rules.admins['$uid']['.write'], false);
assert.match(rules.rules.match['.write'], /root\.child\('admins'\)/);
assert.match(rules.rules.players['$uid']['.write'], /auth\.uid == \$uid/);
assert.match(rules.rules.players['$uid']['.write'], /root\.child\('admins'\)/);
assert.ok(!JSON.stringify(rules).includes('email_verified'));
assert.ok(!html.includes('window.CHRONO_ADMIN_EMAIL'));
console.log('smoke tests: OK');
